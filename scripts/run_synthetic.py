#!/usr/bin/env python3
"""Run the whole diagnostic on synthetic-client-a and write every artifact.

    python scripts/run_synthetic.py                # writes runs/synthetic-client-a/
    python scripts/run_synthetic.py --out /tmp/x   # anywhere else

QuickBooks export -> baseline -> findings -> review gate -> 2-3 SOWs ranked by
annual impact -> side-by-side -> CEO report -> FDE packet -> flywheel prediction row.

Only findings the review gate auto-clears are priced. Held findings are listed in
the report as pending review and stay out of every total.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

# The synthetic demo runs offline. Without a live judge the gate fails closed and
# holds every finding; this flag scores them structurally instead. Production
# leaves it unset (docs/decisions/2026-06-02-offline-deterministic-quality-judge.md).
os.environ.setdefault("NSOS_JUDGE_OFFLINE_DETERMINISTIC", "1")

EXAMPLE = ROOT / "examples" / "synthetic-client-a"
TENANT_ID = "synth-acme-services"
RUN_ID = "synthetic-client-a"
COMMAND = "python scripts/run_synthetic.py"

# Imported after the sys.path line above: this file runs as a script.
import client.onboarding.onboarding as onboarding
import engine.meta_levels.financial.findings as findings_mod
import engine.meta_levels.financial.review_gate as review_gate
import engine.sow.assembly as assembly
import presentation.side_by_side.sbs as sbs_mod
import presentation.exec_report.report_generator as report_mod
import presentation.handoff.packet as packet_mod
import learning.feedback.outcome_loop as outcome_loop


def run(out: Path) -> dict:
    """Execute the real chain into `out`; return the artifacts."""
    out = Path(out)
    export = json.loads((EXAMPLE / "quickbooks_export.json").read_text())
    firm = json.loads((EXAMPLE / "firm.json").read_text())

    # 1. onboarding -> baseline. The connector secret stays server-side; the web gets a scoped token.
    baseline_path, web_token = onboarding.onboard_quickbooks(
        TENANT_ID, "synthetic-placeholder-not-a-secret", export, firm=firm,
        secret_store=onboarding.ConnectorSecretStore(), snapshots_root=out / "snapshots",
    )
    baseline = json.loads(Path(baseline_path).read_text())

    # 2. financial team -> grounded findings
    findings = findings_mod.run_findings(
        baseline, out_path=out / "gauntlet" / "financial" / "findings.jsonl")

    # 3. review gate: only auto-cleared findings get priced
    gate = review_gate.review_findings(findings, run_id=out.name, runs_root=out.parent)
    cleared_ids = {d["finding_id"] for d in gate["decisions"] if d["auto_cleared"]}
    cleared = [f for f in findings if f["id"] in cleared_ids]
    held = [f for f in findings if f["id"] not in cleared_ids]

    # 4. SOW assembly -> 2-3 candidates, ranked by annual impact
    sows = assembly.assemble_sows(cleared, artifacts_dir=out / "sow")

    # 5. side-by-side (WWOD + pillar grade + metrics)
    sbs = sbs_mod.build_side_by_side(sows, baseline)
    sbs_mod.write_artifact(sbs, out / "presentation" / "side-by-side.json")

    # 6. CEO decision report
    report = report_mod.render_sow_report(firm, sows, baseline, pending=held)
    report_path = out / "presentation" / "report.md"
    report_path.write_text(f"> Generated by `{COMMAND}` from examples/synthetic-client-a (synthetic data).\n\n{report}")

    # 7. FDE handoff packet for the recommended SOW
    packet = packet_mod.build_packet(
        run_id=RUN_ID, tenant_id=TENANT_ID, firm=firm, side_by_side=sbs.to_dict())
    packet_mod.export_packet(packet, out / "handoff")

    # 8. outcome flywheel prediction row (fixed ts so reruns are byte-identical)
    ledger = out / "flywheel" / "outcome-ledger.jsonl"
    ledger.unlink(missing_ok=True)
    outcome_loop.record_prediction(packet, ledger=ledger, ts="2026-06-07T00:00:00Z")

    return {
        "baseline": baseline, "web_token": web_token, "findings": findings,
        "gate": gate, "held": held, "sows": sows, "sbs": sbs,
        "report": report, "report_path": report_path, "packet": packet, "ledger": ledger,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "runs" / RUN_ID)
    art = run(ap.parse_args().out)
    print(f"{len(art['findings'])} findings, {len(art['held'])} held for review, "
          f"{len(art['sows'])} SOWs")
    print(f"report: {art['report_path']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
